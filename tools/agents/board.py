#!/usr/bin/env python3
"""Generate docs/agents/BOARD.md from task headers; --check validates without writing.

Task files are docs/agents/tasks/T-NNNN-*.md with a `key: value` header between
`---` fences (see docs/agents/PROTOCOL.md). Standard library only.
"""

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
TASKS = ROOT / 'docs' / 'agents' / 'tasks'
BOARD = ROOT / 'docs' / 'agents' / 'BOARD.md'

STATUSES = ('blocked', 'review', 'changes-requested', 'in-progress', 'ready',
            'backlog', 'accepted', 'integrated', 'rejected')
PRIORITIES = ('P1', 'P2', 'P3')
CLAIMS = ('none', 'implemented', 'tested', 'audit-passed', 'promoted')
LEASES = ('none', 'requested', 'held', 'released')
REQUIRED = ('id', 'title', 'status', 'priority', 'owner', 'reviewers',
            'orchestrator', 'branch', 'base', 'candidate', 'claim', 'lease', 'updated')
ACTIVE = ('blocked', 'review', 'changes-requested', 'in-progress', 'ready', 'backlog')
SHA = re.compile(r'[0-9a-f]{7,40}')
LOG_ENTRY = re.compile(r'^### (\S+) · (\S+) → (\S+) · ([A-Z-]+)\s*$')


def parse_header(text):
    lines = text.splitlines()
    if not lines or lines[0].strip() != '---':
        raise ValueError('missing opening --- header fence')
    header = {}
    for number, line in enumerate(lines[1:], start=2):
        if line.strip() == '---':
            return header
        key, sep, value = line.partition(':')
        if not sep or not key.strip():
            raise ValueError(f'line {number}: expected key: value')
        key = key.strip()
        if key in header:
            raise ValueError(f'line {number}: duplicate key {key}')
        header[key] = value.strip()
    raise ValueError('missing closing --- header fence')


def last_log_entry(text):
    entries = [m for m in (LOG_ENTRY.match(line) for line in text.splitlines()) if m]
    if not entries:
        return ''
    when, sender, _, kind = entries[-1].groups()
    return f'{kind} by {sender} at {when}'


def validate(header, filename):
    errors = [f'missing {key}' for key in REQUIRED if not header.get(key)]
    for key, allowed in (('status', STATUSES), ('priority', PRIORITIES),
                         ('claim', CLAIMS), ('lease', LEASES)):
        if header.get(key) and header[key] not in allowed:
            errors.append(f'{key}={header[key]!r} not in {"/".join(allowed)}')
    task_id = header.get('id', '')
    if not re.fullmatch(r'T-\d{4}', task_id):
        errors.append(f'id {task_id!r} is not T-NNNN')
    elif not filename.startswith(task_id + '-'):
        errors.append(f'filename does not start with {task_id}-')
    for key in ('base', 'candidate'):
        value = header.get(key, 'none')
        if value != 'none' and not SHA.fullmatch(value):
            errors.append(f'{key} {value!r} is not a 7-40 hex commit sha')
    status = header.get('status')
    if status in ('review', 'accepted', 'integrated') and header.get('candidate') == 'none':
        errors.append(f'status {status} requires a candidate sha')
    if status not in (None, 'backlog') and header.get('base') == 'none':
        errors.append(f'status {status} requires a base sha')
    return errors


def load_tasks(task_dir=TASKS):
    tasks, errors = [], []
    for path in sorted(task_dir.glob('T-*.md')):
        text = path.read_text(encoding='utf-8')
        try:
            header = parse_header(text)
        except ValueError as error:
            errors.append(f'{path.name}: {error}')
            continue
        problems = validate(header, path.name)
        errors.extend(f'{path.name}: {problem}' for problem in problems)
        header['_file'] = path.name
        header['_last'] = last_log_entry(text)
        tasks.append(header)
    ids = [task.get('id') for task in tasks]
    errors.extend(f'duplicate id {task_id}' for task_id in sorted({i for i in ids if ids.count(i) > 1}))
    return tasks, errors


def _cell(value):
    return value.replace('|', '\\|')


def render(tasks):
    order = {status: index for index, status in enumerate(STATUSES)}
    tasks = sorted(tasks, key=lambda t: (order.get(t['status'], 99), t['priority'], t['id']))
    out = ['# Agent task board', '',
           'Generated by `tools/agents/board.py` from [tasks/](tasks/). Do not edit by hand.',
           'Only the orchestrator (gpt-6-astra) changes task headers; see [PROTOCOL.md](PROTOCOL.md).', '']
    attention = [t for t in tasks if t['status'] in ('blocked', 'review', 'changes-requested')]
    out += ['## Needs attention', '']
    if attention:
        out += [f'- **{t["id"]}** `{t["status"]}`: {_cell(t["title"])} ({t["_last"] or "no log"})'
                for t in attention]
    else:
        out.append('- Nothing blocked or awaiting review.')
    for heading, group in (('Active', ACTIVE), ('Closed', ('accepted', 'integrated', 'rejected'))):
        rows = [t for t in tasks if t['status'] in group]
        out += ['', f'## {heading}', '']
        if not rows:
            out.append('- None.')
            continue
        out += ['| Task | Status | Pri | Owner | Reviewers | Claim | Candidate | Last message |',
                '| --- | --- | --- | --- | --- | --- | --- | --- |']
        for t in rows:
            out.append(
                f'| [{t["id"]}](tasks/{t["_file"]}): {_cell(t["title"])} | `{t["status"]}` | {t["priority"]} '
                f'| {t["owner"]} | {t["reviewers"]} | {t["claim"]} | {t["candidate"]} | {_cell(t["_last"])} |')
    return '\n'.join(out) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if tasks are invalid or BOARD.md is stale')
    args = parser.parse_args(argv)
    tasks, errors = load_tasks()
    for error in errors:
        print(f'error: {error}', file=sys.stderr)
    if errors:
        return 1
    board = render(tasks)
    if args.check:
        current = BOARD.read_text(encoding='utf-8') if BOARD.exists() else ''
        if current != board:
            print('error: docs/agents/BOARD.md is stale; run tools/agents/board.py', file=sys.stderr)
            return 1
        return 0
    BOARD.write_text(board, encoding='utf-8', newline='\n')
    print(f'wrote {BOARD.relative_to(ROOT)} ({len(tasks)} tasks)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
